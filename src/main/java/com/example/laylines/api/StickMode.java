package com.example.laylines.api;

/**
 * Modes for the Layline Stick.
 * READ_NODE – shows closest node and edge information.
 * READ_EDGE – shows only the closest edge information.
 * DEBUG_PLANT – plants a new node at the clicked block and shows the result.
 */
public enum StickMode {
    READ_NODE,
    READ_EDGE,
    DEBUG_PLANT
}

